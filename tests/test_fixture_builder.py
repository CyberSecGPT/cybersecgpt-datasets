@pytest.mark.parametrize(
    "text",
    [
        "MZ fictional",
        "\x7fELF fictional",
        "#! fictional",
        "authorization: bearer fictional",
        "AWS_SECRET_ACCESS_KEY fictional",
        "confidential fictional",
        "password=fictional",
        "powershell -enc fictional",
        "prompt injection fictional",
        "secret=fictional",
        "person@example.test",
        "Connect to 8.8.8.8",
    ],
)
def test_all_unsafe_marker_classes_are_excluded(text: str) -> None:
    unsafe = generator(
        templates=(
            FixtureTemplate("safe", "natural-language", "safe"),
            FixtureTemplate("unsafe", "natural-language", text),
        )
    )
    result = build_fixture_corpus(request(generators=(unsafe,)))
    assert len(result.manifest.samples) == 1


def test_builder_rejects_no_safe_samples_and_source_reuse() -> None:
    unsafe = generator(
        templates=(FixtureTemplate("unsafe", "natural-language", "secret=value"),)
    )
    with pytest.raises(FixtureBuildError):
        build_fixture_corpus(request(generators=(unsafe,)))
    other = replace(generator(), generator_id="other")
    with pytest.raises(FixtureBuildError):
        build_fixture_corpus(request(generators=(generator(), other)))


