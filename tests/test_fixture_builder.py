def test_builder_rejects_unsafe_derived_path_and_input_limits() -> None:
    unsafe_path = generator(generator_id="../escape")
    with pytest.raises(FixtureBuildError):
        build_fixture_corpus(request(generators=(unsafe_path,)))

    too_many = generator(
        templates=tuple(
            FixtureTemplate(f"item-{index}", "natural-language", f"safe-{index}")
            for index in range(1_025)
        )
    )
    with pytest.raises(FixtureBuildError):
        build_fixture_corpus(request(generators=(too_many,)))

    too_large = generator(
        templates=tuple(
            FixtureTemplate(f"item-{index}", "natural-language", "x" * 65_535)
            for index in range(129)
        )
    )
    with pytest.raises(FixtureBuildError):
        build_fixture_corpus(request(generators=(too_large,)))
