def _build_request() -> BuildRequest:
    return BuildRequest(
        corpus_id=FIRST_PARTY_CORPUS_ID,
        approved_purpose=_APPROVED_PURPOSE,
        distribution_limitations=_DISTRIBUTION_LIMITATIONS,
        notices_sha256=_NOTICES_SHA256,
        sources=approved_first_party_sources(),
        generators=first_party_generators(ACCEPTED_GENERATOR_SOURCE_REVISION),
        observed_tick=0,
        deadline_tick=1,
    )


def _validate_exact_snapshot(manifest: SnapshotManifest) -> None:
    fine_counts = tuple(
        sorted(Counter(item.domain for item in manifest.samples).items())
    )
    _require(
        manifest.corpus_id == FIRST_PARTY_CORPUS_ID
        and manifest.approved_purpose == _APPROVED_PURPOSE
        and manifest.distribution_limitations == _DISTRIBUTION_LIMITATIONS
        and manifest.notices_sha256 == _NOTICES_SHA256
        and len(manifest.sources) == FIRST_PARTY_GENERATOR_COUNT
        and len(manifest.samples) == FIRST_PARTY_SAMPLE_COUNT
        and sum(item.byte_count for item in manifest.samples) == 112_467
        and fine_counts == _EXPECTED_FINE_DOMAIN_COUNTS
        and tuple((item.reason_id, item.count) for item in manifest.exclusions)
        == (("exact-duplicate", 0), ("unsafe-content", 0))
        and bool(manifest.manifest_sha256)
    )


def build_first_party_snapshot() -> BuildResult:
    """Build and replay the exact accepted-source snapshot entirely in memory."""

    request = _build_request()
    result = build_fixture_corpus(request)
    _validate_exact_snapshot(result.manifest)
    _require(verify_fixture_replay(request, result))
    return result


def project_tokenizer_admission_manifest(
    manifest: SnapshotManifest, dataset_implementation_revision: str
) -> TokenizerAdmissionProjection:
    """Project the exact dataset snapshot into the pinned tokenizer contract."""

    _require(
        type(dataset_implementation_revision) is str
        and _GIT_REVISION.fullmatch(dataset_implementation_revision) is not None
    )
    _require(manifest == build_first_party_snapshot().manifest)
    _require(
        all(
            source.approved()
            and source.rights_decision is ReviewDecision.APPROVED
            and source.safety_decision is ReviewDecision.APPROVED
            and source.contamination_decision is ReviewDecision.APPROVED
            for source in manifest.sources
        )
    )
    projection = TokenizerAdmissionProjection(
        corpus_id=manifest.corpus_id,
        approved_purpose=manifest.approved_purpose,
        artifact_distribution_terms=manifest.distribution_limitations,
        sources=tuple(
            TokenizerSourceProjection(
                source_id=source.source_id,
                origin_ref=source.canonical_origin,
                acquisition_method=source.acquisition_method,
                acquired_at=source.acquired_at,
                source_revision=source.source_revision,
                source_sha256=source.source_sha256,
                license_expression=FIRST_PARTY_LICENSE_EXPRESSION,
                obligations_sha256=source.obligations_sha256,
                reviewer_id=source.reviewer_id,
                reviewed_at=source.reviewed_at,
                rights_decision="approved",
                sensitive_data_decision="clean",
                contamination_decision="clean",
                acquisition_allowed=source.acquisition_allowed,
                processing_allowed=source.processing_allowed,
                training_allowed=source.tokenizer_training_allowed,
                derived_statistics_allowed=source.derived_statistics_allowed,
                artifact_distribution_allowed=(
                    source.tokenizer_artifact_distribution_allowed
                ),
            )
            for source in manifest.sources
        ),
        transformations=tuple(
            TokenizerTransformationProjection(
                stage_id=stage.stage_id,
                tool_id=f"{stage.tool_id}@{stage.tool_revision}",
                configuration_sha256=stage.configuration_sha256,
            )
            for stage in manifest.transformations
        )
        + (
            TokenizerTransformationProjection(
                stage_id="admission-projection",
                tool_id=(
                    f"{TOKENIZER_PROJECTION_PROFILE_VERSION}@"
                    f"{dataset_implementation_revision}"
                ),
                configuration_sha256=manifest.manifest_sha256,
            ),
        ),
        samples=tuple(
            TokenizerSampleProjection(
                sample_id=sample.sample_id,
                source_id=sample.source_id,
                domain=_TOKENIZER_DOMAIN_BY_FINE_DOMAIN[sample.domain],
                byte_count=sample.byte_count,
                content_sha256=sample.content_sha256,
            )
            for sample in manifest.samples
        ),
        exclusion_counts=tuple(
            (item.reason_id, item.count) for item in manifest.exclusions
        ),
    ).with_computed_digest()
    domain_counts = tuple(
        sorted(Counter(item.domain for item in projection.samples).items())
    )
    _require(
        domain_counts == _EXPECTED_TOKENIZER_DOMAIN_COUNTS
        and projection.manifest_sha256 != manifest.manifest_sha256
    )
    return projection


def first_party_snapshot_evidence(
    dataset_implementation_revision: str,
) -> FirstPartySnapshotEvidence:
    """Return content-minimized exact snapshot and projection identities."""

    result = build_first_party_snapshot()
    projection = project_tokenizer_admission_manifest(
        result.manifest, dataset_implementation_revision
    )
    return FirstPartySnapshotEvidence(
        schema_version=FIRST_PARTY_SNAPSHOT_EVIDENCE_SCHEMA_VERSION,
        snapshot_profile_version=FIRST_PARTY_SNAPSHOT_PROFILE_VERSION,
        projection_profile_version=TOKENIZER_PROJECTION_PROFILE_VERSION,
        accepted_generator_source_revision=ACCEPTED_GENERATOR_SOURCE_REVISION,
        dataset_implementation_revision=dataset_implementation_revision,
        tokenizer_verifier_revision=TOKENIZER_VERIFIER_REVISION,
        owner_acceptance_sha256=OWNER_ACCEPTANCE_SHA256,
        dataset_manifest_sha256=result.manifest.manifest_sha256,
        dataset_replay_sha256=result.replay_sha256,
        tokenizer_admission_manifest_sha256=projection.manifest_sha256,
        source_count=len(result.manifest.sources),
        sample_count=len(result.manifest.samples),
        total_byte_count=sum(item.byte_count for item in result.manifest.samples),
        fine_domain_counts=tuple(
            sorted(Counter(item.domain for item in result.manifest.samples).items())
        ),
        tokenizer_domain_counts=tuple(
            sorted(Counter(item.domain for item in projection.samples).items())
        ),
        exclusion_counts=projection.exclusion_counts,
    )
